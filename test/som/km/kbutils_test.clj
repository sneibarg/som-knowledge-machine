  (is (= (term "(a b)") (kb/set-elements (term "(:set a b)"))))
  (is (= (term "(a b)") (kb/seq-elements (term "(:seq a b)")))))

(deftest descriptions-constraints-and-operators
  (is (kb/description? (term "'(every Dog)")))
  (is (kb/description? (term "(the-class Dog)")))
  (is (kb/quoted-description? (term "'(every Dog)")))
  (is (not (kb/quoted-description? (term "'(a Dog)"))))
  (is (kb/the-class? (term "(the-class Dog)")))
  (is (kb/val-constraint? (term "(must-be-a Cat)")))
  (is (kb/val-constraint? (term "(<> 23)")))
  (is (kb/set-constraint? :incomplete))
