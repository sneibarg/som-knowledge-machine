(ns som.km.kbutils-test
  (:require [clojure.test :refer [deftest is]]
            [som.km.kbutils :as kb]
            [som.km.read :as read]
            [som.km.term :as term]
            [som.km.utils :as utils]))

(defn- term [text]
  (:value (read/read-term text)))

(deftest tolerance-is-the-header-binding
  (is (= 0.0001 kb/tolerance))
  (is (not (kb/km-equal? 0.00001 0.00002)))
  (is (kb/km-equal? 4.99999 5.0))
  (is (not (kb/km-equal? 499999 500000)))
  (is (kb/km-equal? 1 1.0))
  (is (kb/km-equal? 1/2 0.5))
  (is (not (utils/equal? 1 1.0)))
  (is (not (utils/eql? 1 1.0))))

(deftest km-equal-treats-nil-and-symbols-by-identity
  (is (kb/km-equal? nil nil))
  (is (kb/km-equal? nil (symbol "nil")))
  (is (kb/km-equal? (symbol "nil") nil))
  (is (not (utils/equal? nil (symbol "nil"))))
  (is (not (kb/km-equal? (symbol "t") (symbol "T"))))
  (is (not (kb/km-equal? (symbol "a") (symbol "b"))))
  (is (kb/km-equal? :set :set))
  (is (not (kb/km-equal? :set (symbol "set")))))

(deftest km-equal-rejects-a-copied-existential-and-accepts-a-copied-path
  (is (utils/equal? (term "(a Car)") (term "(a Car)")))
  (is (not (kb/km-equal? (term "(a Car)") (term "(a Car)"))))
  (is (kb/km-equal? (term "(the age of Fred)") (term "(the age of Fred)")))
  (is (not (kb/km-equal? (term "(:pair (a Move) 1)") (term "(:pair (a Move) 1)"))))
  (is (kb/km-equal? (term "(:pair a 1)") (term "(:pair a 1.0)")))
  (is (not (kb/km-equal? (term "(:function foo)") (term "(:function foo)")))))

(deftest sets-bags-and-sequences-compare-on-their-own-rules
  (is (kb/km-equal? (term "(:set a b)") (term "(:set b a)")))
  (is (kb/km-equal? (term "(:set a a)") (term "(:set a)")))
  (is (kb/km-equal? (term "(:set (a Car) (a Dog))")
                    (term "(:set (a Car) (a Dog))")))
  (is (not (kb/km-equal? (term "(:set (a Car) (a Dog))")
                         (term "(:set (a Dog) (a Car))"))))
  (is (not (kb/km-equal? (term "(:seq a b)") (term "(:seq b a)"))))
  (is (kb/km-equal? (term "(:seq 1)") (term "(:seq 1.0)")))
  (is (not (utils/equal? (term "(:seq 1)") (term "(:seq 1.0)"))))
  (is (kb/km-bag-equal? (term "(:bag a b)") (term "(:bag b a)")))
  (is (kb/km-equal? (term "(:bag a b)") (term "(:bag b a)")))
  (is (not (kb/km-equal? (term "(:bag a a)") (term "(:bag a)"))))
  (is (not (kb/km-equal? (term "(:set a b)") (term "(:seq a b)")))))

(deftest remove-dup-instances-keeps-the-earlier-value
  (is (= (term/km-list 5.0)
         (kb/remove-dup-instances (term/km-list 5.0 4.99999))))
  (is (= (term/km-list 4.99999)
         (kb/remove-dup-instances (term/km-list 4.99999 5.0))))
  (is (= (term "((:set a b))")
         (kb/remove-dup-instances (term "((:set a b) (:set b a))"))))
  (is (= (term/km-list nil)
         (kb/remove-dup-instances (term/km-list nil (symbol "nil")))))
  (is (= (term/km-list (symbol "nil"))
         (kb/remove-dup-instances (term/km-list (symbol "nil") nil)))))

