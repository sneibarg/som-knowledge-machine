  (is (kb/slot-object? :age))
  (is (not (kb/slot-object? nil)))
  (is (not (kb/slot-object? "age")))
  (is (kb/path? nil))
  (is (kb/path? (term "(a b)")))
  (is (not (kb/path? (symbol "a"))))
  (is (kb/kb-object? (symbol "t")))
  (is (kb/kb-object? (symbol "f")))
  (is (kb/kb-object? (symbol "T")))
  (is (kb/kb-object? (symbol "Cat")))
  (is (kb/kb-object? :foo))
  (is (not (kb/kb-object? nil)))
  (is (not (kb/kb-object? (symbol "nil"))))
  (is (not (kb/kb-object? (symbol "[tag]"))))
  (is (not (kb/kb-object? :set)))
  (is (not (kb/kb-object? :incomplete)))
  (is (kb/km-set? (term "(:set a)")))
  (is (kb/km-seq? (term "(:seq a)")))
  (is (kb/km-bag? (term "(:bag a)")))
  (is (kb/km-pair-value? (term "(:pair a 1)")))
  (is (kb/km-args? (term "(:args a b)")))
  (is (kb/km-function? (term "(:function foo)")))
  (is (kb/km-default? (term "(:default a)")))
  (is (kb/km-triple? (term "(:triple a b c)")))
  (is (kb/km-triple? (term "(:triple a [1] b c)")))
  (is (not (kb/km-triple? (term "(:triple a b c d)"))))
