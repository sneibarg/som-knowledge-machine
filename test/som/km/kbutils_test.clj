(deftest values-move-between-a-value-and-a-list
  (is (nil? (kb/val-to-vals nil)))
  (is (nil? (kb/val-to-vals (symbol "nil"))))
  (is (= (term "(a (:set b))")
         (kb/val-to-vals (term "(:set a (:set b))"))))
  (is (= (term "(a)") (kb/val-to-vals (symbol "a"))))
  (is (= (term "((a Car))") (kb/val-to-vals (term "(a Car)"))))
  (is (nil? (kb/vals-to-val nil)))
  (is (= (symbol "a") (kb/vals-to-val (term "(a)"))))
  (is (= (term "(:set a b)") (kb/vals-to-val (term "(a b)"))))
  (is (= (term "(:set a b . c)") (kb/vals-to-val (term "(a b . c)"))))
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"single value"
        (kb/vals-to-val (symbol "a"))))
  (is (= (term "(a b c d e f g h)")
         (kb/flatten-sets (term "((:set a b (:set c (:set d e)) f (:set g h)))"))))
  (is (= (term "(b)") (kb/flatten-set (symbol "b"))))
  (is (= (term/km-list nil) (kb/flatten-set nil)))
  (is (= (term "(x y z)") (kb/&-expr-to-vals (term "(x & y & z)"))))
  (is (= (term "((a Car) (a Dog))")
         (kb/&-expr-to-vals (term "((a Car) & (a Dog))"))))
  (is (= (term "((a Car))") (kb/&-expr-to-vals (term "(a Car)"))))
  (is (= (term "(x)") (kb/&-expr-to-vals (symbol "x"))))
  (is (= (term "(a b d e f g)")
         (kb/&-expr-to-vals (term "((a & (b & d)) & (e & (f & g)))"))))
  (is (= (term "(x y)") (kb/&-expr-to-vals (term "(x & y z)"))))
  (is (nil? (kb/vals-to-&-expr nil)))
  (is (= (symbol "a") (kb/vals-to-&-expr (term "(a)"))))
  (is (= (term "(a & b & c)") (kb/vals-to-&-expr (term "(a b c)"))))
  (let [ab (term/km-list (symbol "a") (symbol "b"))
        cd (term/km-list (symbol "c") (symbol "d"))
        ef (term/km-list (symbol "e") (symbol "f"))
        amp (symbol "&&")
        joined (term/km-list ab amp cd amp ef)]
    (is (= ab (kb/valsets-to-&&-exprs (term/km-list ab))))
    (is (= (term/km-list joined)
           (kb/valsets-to-&&-exprs (term/km-list ab cd ef))))
    (is (= (term/km-list ab)
           (kb/&&-exprs-to-valsets ab)))
    (is (= (term/km-list ab cd)
           (kb/&&-exprs-to-valsets (term/km-list (term/km-list ab amp cd)))))
    (is (= (term/km-list ab cd ef)
           (kb/&&-exprs-to-valsets (term/km-list joined))))
    (is (= (term/km-list ab cd ef)
           (kb/&&-exprs-to-valsets
            (term/km-list (term/km-list ab amp (term/km-list (term/km-list cd amp ef)))))))
    (is (= (term/km-list ab cd ef)
           (kb/&&-exprs-to-valsets
            (term/km-list (term/km-list (term/km-list (term/km-list ab amp cd)) amp ef)))))
    (let [wrapped (term/km-list (symbol "a") (term/km-list ab amp cd))]
      (is (= (term/km-list wrapped)
             (kb/&&-exprs-to-valsets wrapped))))))

(deftest val-sets-to-expr-follows-the-defined-function
  (is (= (symbol "a") (kb/val-sets-to-expr (term "((a))"))))
  (is (= (term "(:set a b)") (kb/val-sets-to-expr (term "((a b))"))))
  (is (= (term "(a & b & c)")
         (kb/val-sets-to-expr (term "((a) (b) (c))") :single-valued? true)))
  ;; The comment says this is an error and the value (a & c). The
  ;; function joins the long list and continues, so the value is
  ;; ((a & b) & c).
  (is (= (term "((a & b) & c)")
         (kb/val-sets-to-expr (term "((a b) (c))") :single-valued? true)))
  (is (= (term "((a b) && (b) && (c d))")
         (kb/val-sets-to-expr (term "((a b) (b) (c d))"))))
  (is (= (term "(:set a b c d)")
         (kb/val-sets-to-expr (term "((a b) (b) (c d))")
                              :combine-values-by-appending? true)))
  (is (= (term "(a & b)")
         (kb/val-sets-to-expr (term "((a) (b) (a))") :single-valued? true)))
  (is (= (term "((a) && (b))")
         (kb/val-sets-to-expr (term "((a) () (b))"))))
  (is (= (term "((a) && (nil) && (b))")
         (kb/val-sets-to-expr (term "((a) (nil) (b))"))))
  (is (= (term "((a) && (b))")
         (kb/val-sets-to-expr (term "(a (b))")))))
